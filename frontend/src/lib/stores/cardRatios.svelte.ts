// 卡片宽高比跨导航持久化。
//
// 网格墙（PosterWall / UnifiedWall）按图片实际宽高比给卡片定形：宽图跨 2 列、
// 竖图/方图单列。该比例由 <img> onload 测得，原先存在组件内的 $state 里。
// 从详情/播放器返回媒体库时组件重建、比例表清空 → 只加载视口内的图片，
// 用户此前滚过（现已在视口外、懒加载不触发）的卡片退回默认比例 →
// 卡片高度与离开时不一致 → 锚点卡片的绝对位置整体偏移 → 滚动恢复落点错位。
//
// 放到 module 级 $state：跨导航保留，返回首帧即用离开时的比例渲染，
// 布局与离开时完全一致，锚点恢复一步到位（与 mediaScroll 同一思路）。
//
// 键为媒体 id（字符串）。同一媒体再次出现时比例不变；若海报被替换，
// 新的图片加载后 onload 会覆盖旧值，最坏情况只是一次首帧形状偏差。
